function __($key) {
    global $translations, $userLang;
    if (isset($translations[$key]) && isset($translations[$key][$userLang])) {
        return $translations[$key][$userLang];
    }
    // Fallback to English if translation missing
    if (isset($translations[$key]['en'])) {
        return $translations[$key]['en'];
    }
    // Return key as is if not defined
    return $key;
}
